"""
Local specialties: which of the city's signature dishes a restaurant is known for.

Two files per city (paths in shared/cities.json):
- data/local_dishes/<city>.json - the signature dishes, written by hand.
- data/specialties/<city>.json - generated by
  `python -m restaurants.tools.find_specialties`, which reads what critics'
  guides and the restaurant's own website say about each recognised place and
  asks Claude which signature dishes it is *known for* (not merely serves).
  Every label carries the exact words that justify it.

Searches only read the generated file - no network, no model calls.
"""

import json
import os
import re
import unicodedata

from restaurants import matching
from server import cities

MATCH_RADIUS_M = 150

_cache = {}


def _read(path):
    try:
        mtime = os.path.getmtime(path)
    except OSError:
        return None
    hit = _cache.get(path)
    if hit and hit[0] == mtime:
        return hit[1]
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
    except ValueError:
        data = None
    _cache[path] = (mtime, data)
    return data


def load_dishes(city):
    """{key: dish} from the hand-written list, or {} if the city has none."""
    if not city.get("local_dishes"):
        return {}
    data = _read(cities.data_path(city["local_dishes"])) or {}
    return {d["key"]: d for d in data.get("dishes", [])}


def load(city):
    """Generated records, each {'name', 'lat', 'lon', 'known_for': [...]}, with
    every dish key checked against the dish list."""
    if not city.get("specialties"):
        return []
    dishes = load_dishes(city)
    data = _read(cities.data_path(city["specialties"])) or {}
    records = []
    for place in data.get("places", []):
        known = [dict(k, label=dishes[k["dish"]]["label"])
                 for k in place.get("known_for", []) if k.get("dish") in dishes]
        if known and place.get("lat") is not None:
            records.append(dict(place, known_for=known))
    return records


def for_place(place, records):
    """The specialties of a merged place, found through its recognition entries
    (the tool labels recognised places by the names their critics use)."""
    found, seen = [], set()
    for entry in place.get("recognition", []):
        for record in records:
            if not matching.names_match(entry["name"], record["name"]):
                continue
            if entry.get("lat") is not None and matching.distance_m(
                    entry["lat"], entry["lon"], record["lat"], record["lon"]) > MATCH_RADIUS_M:
                continue
            for item in record["known_for"]:
                if item["dish"] not in seen:
                    seen.add(item["dish"])
                    found.append(item)
    return found


# ---------------------------------------------------------------------------
# Text helpers for the tool
# ---------------------------------------------------------------------------

_QUOTES = str.maketrans({"‘": "'", "’": "'", "“": '"', "”": '"',
                         "‐": "-", "‑": "-", "‒": "-", "–": "-",
                         "—": "-", " ": " ", " ": " "})


def normalize_text(text):
    """Lowercase, plain quotes and dashes, single spaces - for comparing quotes."""
    text = unicodedata.normalize("NFKC", text or "").translate(_QUOTES)
    return re.sub(r"\s+", " ", text).strip().lower()


def quote_in(quote, text):
    """True if `quote` appears word for word in `text` (ignoring case,
    whitespace and curly-vs-straight punctuation). Guards against a model
    paraphrasing or inventing evidence."""
    q = normalize_text(quote).strip(" .\"'")
    return len(q) >= 8 and q in normalize_text(text)


def name_variants(name):
    """Ways an article may write a restaurant's name."""
    base = normalize_text(name)
    variants = {base, re.sub(r"^the ", "", base), base.replace("&", "and"), base.replace(" and ", " & ")}
    plain = unicodedata.normalize("NFKD", base).encode("ascii", "ignore").decode()
    variants.add(plain)
    return sorted((v for v in variants if len(v) >= 3), key=len, reverse=True)


def passages(name, text, before=300, after=1500, limit=4000):
    """The parts of a long article that are about one restaurant: a window
    around each mention of its name, merged where they overlap. '' if the
    name never appears."""
    lowered = normalize_text(text)
    spans = []
    for variant in name_variants(name):
        for m in re.finditer(r"(?<![a-z0-9])" + re.escape(variant) + r"(?![a-z0-9])", lowered):
            spans.append((max(0, m.start() - before), min(len(lowered), m.end() + after)))
    if not spans:
        return ""
    spans.sort()
    merged = [list(spans[0])]
    for start, end in spans[1:]:
        if start <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], end)
        else:
            merged.append([start, end])
    plain = re.sub(r"\s+", " ", unicodedata.normalize("NFKC", text).translate(_QUOTES)).strip()
    if len(plain) != len(lowered):     # a character whose lowercase is longer
        plain = lowered
    return " … ".join(plain[s:e] for s, e in merged)[:limit]
